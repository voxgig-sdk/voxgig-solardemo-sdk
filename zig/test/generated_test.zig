    const offline = h.jo(&.{.{ "net", h.jo(&.{.{ "offline", h.vbool(true) }}) }});
    switch (sdk.test_sdk(offline, vnull()).planet(vnull()).stream("list", vnull(), vnull())) {
        .err => |er| try std.testing.expect(std.mem.indexOf(u8, er.msg, "offline") != null),
