    if (fh.fh_has_feature("rbac")) {
        const deny = h.jo(&.{.{ "feature", h.jo(&.{.{ "rbac", h.jo(&.{
            .{ "active", h.vbool(true) },
            .{ "deny", h.vbool(true) },
