        switch (sdk.test_sdk(vnull(), deny).planet(vnull()).stream("list", vnull(), vnull())) {
            .err => |er| try std.testing.expect(std.mem.eql(u8, er.code, "rbac_denied")),
            .ok => try std.testing.expect(false),
        }
    }
}

